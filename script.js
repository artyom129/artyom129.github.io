const supported = ["en", ...Object.keys(T)];

function setLanguage(lang) {
  const dict = T[lang];
  nodes.forEach(node => {
    node.textContent = (dict && dict[node.dataset.i18n]) || english.get(node);
  });
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  if (picker) picker.value = lang;
  try { localStorage.setItem("lang", lang); } catch (_) { /* private mode */ }
}

function initialLanguage() {
  try {
    const saved = localStorage.getItem("lang");
    if (supported.includes(saved)) return saved;
  } catch (_) { /* private mode */ }
  const browser = (navigator.language || "en").slice(0, 2).toLowerCase();
  return supported.includes(browser) ? browser : "en";
}

if (picker) picker.addEventListener("change", () => setLanguage(picker.value));
setLanguage(initialLanguage());

